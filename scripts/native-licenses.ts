// Writes native/THIRD-PARTY-LICENSES.md: the license, with its copyright notice, of every crate compiled into
// cavvy-native for the targets it's shipped on (macOS and Linux), from Cargo's own copies of them. A crate licensed
// MIT among others is given under MIT. Run after changing native/Cargo.lock:
//
//   bun scripts/native-licenses.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import { dirname, join } from "path";

const native = join(import.meta.dir, "..", "native");
const run = (args: string[]) => {
    const r = Bun.spawnSync(args, { cwd: native, stdout: "pipe", stderr: "pipe" });
    if (r.exitCode) throw new Error(`${args.join(" ")}: ${r.stderr}`);
    return r.stdout.toString();
};
const shipped = new Set<string>();
for (const target of ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-unknown-linux-gnu"]) {
    for (const line of run(["cargo", "tree", "-e", "normal", "--prefix", "none", "--format", "{p}", "--locked", "--target", target]).split("\n")) {
        const m = /^(\S+) v(\S+)/.exec(line);
        if (m && m[1] !== "cavvy-native") shipped.add(`${m[1]} ${m[2]}`);
    }
}
const meta = JSON.parse(run(["cargo", "metadata", "--format-version", "1", "--locked"])) as { packages: { name: string; version: string; license?: string; manifest_path: string }[] };
const sections: string[] = [];
for (const p of meta.packages.filter((p) => shipped.has(`${p.name} ${p.version}`)).sort((a, b) => a.name.localeCompare(b.name))) {
    const dir = dirname(p.manifest_path);
    // LICENSE-MIT and the like, or a LICENSES folder of them (REUSE's layout).
    const files = readdirSync(dir).filter((f) => /^(LICEN[CS]E|COPYING|UNLICENSE)/i.test(f)).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? readdirSync(join(dir, f)).map((g) => join(f, g)) : [f]));
    const mit = /\bMIT\b/.test(p.license ?? "");
    // Under MIT where it's offered; then whatever else the crate has (zlib, Unicode), as it ships them.
    const pick = files.filter((f) => (mit ? /MIT/i.test(f) : !/APACHE/i.test(f)) || /UNICODE|ZLIB/i.test(f) || (!mit && files.length === 1));
    const chosen = pick.length ? pick : files.filter((f) => !/APACHE/i.test(f));
    const texts = chosen.map((f) => readFileSync(join(dir, f), "utf8").trim());
    if (!texts.length) throw new Error(`${p.name} ${p.version} (${p.license}) has no license file to include`);
    sections.push(`## ${p.name} ${p.version}\n\nLicense: ${p.license}${mit ? " (used under MIT)" : ""}\n\n${texts.map((t) => "```\n" + t + "\n```").join("\n\n")}`);
}
writeFileSync(join(native, "THIRD-PARTY-LICENSES.md"), `# cavvy-native: third-party licenses\n\ncavvy-native is built from these crates. Generated by \`bun scripts/native-licenses.ts\` from native/Cargo.lock.\n\n${sections.join("\n\n")}\n`);
console.log(`${sections.length} crates`);
